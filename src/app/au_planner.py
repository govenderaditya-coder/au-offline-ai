#!/usr/bin/env python3
"""
AU Autonomous Goal Planner & Execution Engine
Decomposes complex, multi-stage user goals into structured, executable phases.
Generates persistent markdown plans into ~/Documents/AU_Notes/Plans/
and executes subtasks sequentially through the central AUOrchestrator queue.
"""

import os
import re
import sys
import json
import time
from datetime import datetime
from typing import List, Dict, Any, Optional

PLANS_DIR = os.path.expanduser("~/Documents/AU_Notes/Plans")
os.makedirs(PLANS_DIR, exist_ok=True)

class AUPlanner:
    def __init__(self, orchestrator=None):
        self.orchestrator = orchestrator

    def create_plan(self, goal: str, context: Optional[str] = None) -> Dict[str, Any]:
        """Decomposes a user goal into structured phases and actionable steps."""
        plan_id = f"plan_{int(time.time())}"
        timestamp_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        # System prompt for plan generation
        system_prompt = (
            "You are AU's Senior Architect & Planning Engine. Break down the user's high-level goal into a clear, "
            "rigorous, 4-phase execution plan. Each phase must contain 2-4 concrete, verifiable checklist items.\n"
            "Output JSON with the following structure:\n"
            "{\n"
            '  "title": "Short descriptive title",\n'
            '  "phases": [\n'
            '    {"name": "Phase 1: Research & Analysis", "tasks": ["Task 1", "Task 2"]},\n'
            '    {"name": "Phase 2: Implementation", "tasks": ["Task 1", "Task 2"]},\n'
            '    {"name": "Phase 3: Verification & Testing", "tasks": ["Task 1"]},\n'
            '    {"name": "Phase 4: Summary & Delivery", "tasks": ["Task 1"]}\n'
            "  ]\n"
            "}\n"
            "Return ONLY raw valid JSON, no conversational markdown wrap."
        )

        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": f"Goal: {goal}\nAdditional Context: {context or 'None'}"}
        ]

        # Use orchestrator model router if available, else direct Ollama query
        plan_data = None
        if self.orchestrator:
            try:
                raw_json = self.orchestrator.router.query(messages, keep_alive="3m")
                # Strip markdown codeblocks if model added them
                clean_json = re.sub(r"```(?:json)?|```", "", raw_json).strip()
                plan_data = json.loads(clean_json)
            except Exception:
                pass

        # Fallback heuristic plan if model unavailable or JSON parse failed
        if not plan_data:
            plan_data = {
                "title": f"Plan: {goal[:40]}",
                "phases": [
                    {"name": "Phase 1: Analysis & Inspection", "tasks": [f"Inspect codebase for '{goal[:30]}'", "Identify dependencies and impacted files"]},
                    {"name": "Phase 2: Execution & Editing", "tasks": ["Implement core modifications", "Apply surgical diff patches"]},
                    {"name": "Phase 3: Verification & Testing", "tasks": ["Run syntax and compilation checks", "Verify memory footprint"]},
                    {"name": "Phase 4: Finalization", "tasks": ["Generate commit and update documentation", "Report completion summary"]}
                ]
            }

        # Format markdown document
        md_lines = [
            f"# 🎯 {plan_data.get('title', 'Execution Plan')}",
            f"*Generated by AU Autonomous Planner on {timestamp_str}*",
            f"**Primary Objective:** {goal}\n",
            "---",
            "## 📋 Execution Roadmap\n"
        ]

        for phase in plan_data.get("phases", []):
            md_lines.append(f"### {phase.get('name', 'Phase')}")
            for t in phase.get("tasks", []):
                md_lines.append(f"- [ ] {t}")
            md_lines.append("")

        md_content = "\n".join(md_lines)
        plan_filename = f"{plan_id}_{re.sub(r'[^a-zA-Z0-9_]', '_', goal[:25])}.md"
        plan_path = os.path.join(PLANS_DIR, plan_filename)

        with open(plan_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        return {
            "plan_id": plan_id,
            "title": plan_data.get("title"),
            "plan_path": plan_path,
            "markdown": md_content,
            "phases": plan_data.get("phases", [])
        }

    def list_saved_plans(self) -> List[Dict[str, str]]:
        """Lists all existing plans saved in ~/Documents/AU_Notes/Plans/."""
        if not os.path.exists(PLANS_DIR):
            return []
        plans = []
        for f in sorted(os.listdir(PLANS_DIR), reverse=True):
            if f.endswith(".md"):
                full_path = os.path.join(PLANS_DIR, f)
                plans.append({"filename": f, "path": full_path})
        return plans

if __name__ == "__main__":
    planner = AUPlanner()
    print("Testing AU Autonomous Planner...")
    res = planner.create_plan("Upgrade AU with screen vision and autonomous learning")
    print(f"Created Plan: {res['title']}")
    print(f"Saved at: {res['plan_path']}")
    print("\nGenerated Markdown Preview:")
    print(res["markdown"][:400] + "...")
